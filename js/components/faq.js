/**
 * @returns {string} HTML блока FAQ
 */
export function renderFaq() {
  const items = FAQ_DATA.map((item, i) => `
    <div class="faq-item" id="faq-item-${i}">
      <button
        class="faq-question btn-press"
        aria-expanded="false"
        onclick="toggleFaq(${i})"
      >
        <span>${item.q}</span>
        <i data-lucide="chevron-down" class="faq-chevron w-4 h-4" id="faq-chevron-${i}"></i>
      </button>
      <div class="faq-answer" id="faq-answer-${i}" hidden>
        <p>${item.a}</p>
      </div>
    </div>
  `).join('');

  return `
    <section id="faq" class="section">
      <h2 class="section-title">Вопросы и ответы</h2>
      <div class="faq-list">
        ${items}
      </div>
    </section>
  `;
}
